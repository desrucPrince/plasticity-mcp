// G4: the native exporters write the staging path and the OS user name into the file header.

const STAGING = "/Users/jane.doe/work/models/.plasticity-step-AbC123/geometry.step";
const stepFile = (name: string, author: string, organisation: string) => [
  "ISO-10303-21;", "HEADER;", "", "/* File generated by HOOPS Exchange Version 25.8.0 */", "",
  "FILE_DESCRIPTION(('HOOPS Exchange Step'),'2;1');", "",
  `FILE_NAME('${name}',`, "'2026-11-16T16:08:24-07:00',", `('${author}'),`, `('${organisation}'),`, "'HOOPS Exchange 2025.8',", "'HOOPS Exchange',", "'Unknown authorisation');", "",
  "FILE_SCHEMA( ('AP203_CONFIGURATION_CONTROLLED_3D_DESIGN_OF_MECHANICAL_PARTS_AND_ASSEMBLIES_MIM_LF') );", "", "ENDSEC;", "", "DATA;",
  "#1=PRODUCT('jane.doe','/Users/jane.doe/data note','',(#2));", "#2=PRODUCT_CONTEXT('',#3,'mechanical');", "ENDSEC;", "END-ISO-10303-21;", "",
].join("\n");

test("STEP header: name is the output base name, author and organisation are empty, the data section is byte-identical", () => {
  const input = stepFile(STAGING, "jane.doe", "Unknown organisation");
  const output = sanitizeStepHeader(input, "box.step");
  assert.match(output, /FILE_NAME\('box\.step',\n'2026-11-16T16:08:24-07:00',\n\(''\),\n\(''\),\n'HOOPS Exchange 2025\.8',\n'HOOPS Exchange',\n'Unknown authorisation'\);/);
  assert.equal(output.slice(output.indexOf("DATA;")), input.slice(input.indexOf("DATA;")), "data section unchanged, including text that names the user");
  assert.equal(output.slice(0, output.indexOf("FILE_NAME(")), input.slice(0, input.indexOf("FILE_NAME(")));
  assert.equal(output.includes("jane.doe/work"), false);
  assert.equal(output.slice(0, output.indexOf("DATA;")).includes("jane.doe"), false);
});

test("STEP header: quotes in names are escaped and a header without FILE_NAME is left alone", () => {
  assert.match(sanitizeStepHeader(stepFile(STAGING, "a", "b"), "it's.step"), /FILE_NAME\('it''s\.step',/);
  assert.match(sanitizeStepHeader(stepFile("x", "a", "b"), "naïve.step"), /FILE_NAME\('na\\X2\\00EF\\X0\\ve\.step',/);
  const bare = "ISO-10303-21;\nHEADER;\nENDSEC;\nDATA;\nENDSEC;\nEND-ISO-10303-21;\n";
  assert.equal(sanitizeStepHeader(bare, "a.step"), bare);
  // Commas, parentheses and doubled quotes inside the quoted values do not end an argument.
  const odd = stepFile("n''(x),(1)", "a,b)", "c,(d");
  const cleaned = sanitizeStepHeader(odd, "k.step");
  assert.match(cleaned, /FILE_NAME\('k\.step',\n'2026-11-16T16:08:24-07:00',\n\(''\),\n\(''\),\n'HOOPS Exchange 2025\.8',/);
});

