// The staging-folder guard compares bytes: UTF-8, and each format's own encoding of the folder name.
test("cadExportNamesFolder finds a non-ASCII staging folder in UTF-8, in STEP escapes and as IGES blanks", () => {
  const folder = "/tmp/x/raw-dïr 模型 o'k/.plasticity-step-Ab";
  // The STEP exporter writes \S\ for a Latin-1 character, \X2\..\X0\ for others and doubles the quote (seen live).
  const step = Buffer.from(`FILE_NAME('/tmp/x/raw-d\\S\\or \\X2\\6A21578B\\X0\\ o''k/.plasticity-step-Ab/geometry.step',\n'2026');`, "latin1");
  assert.equal(cadExportNamesFolder(step, folder, "step"), true);
  assert.equal(cadExportNamesFolder(Buffer.from("FILE_NAME('part.step');"), folder, "step"), false);
  // An escaped backslash is not the start of another escape.
  assert.equal(cadExportNamesFolder(Buffer.from("'a\\\\S\\\\b'", "latin1"), "a\\S\\b", "step"), true);
  // Parasolid writes the folder as UTF-8 bytes.
  assert.equal(cadExportNamesFolder(Buffer.concat([Buffer.from("KEY="), Buffer.from(`${folder}/geometry;`, "utf8")]), folder, "parasolid"), true);
  assert.equal(cadExportNamesFolder(Buffer.from("KEY=part;", "utf8"), folder, "parasolid"), false);
  // The IGES exporter writes every byte of a non-ASCII character as a blank, and the Global section wraps at column 72.
  const blanked = Buffer.from(Buffer.from(folder, "utf8").map((byte) => (byte >= 0x80 ? 0x20 : byte))).toString("latin1");
  const wrapped = `1H,,1H;,,99H${blanked}/geometry.igs,`;
  const igesText = [wrapped.slice(0, 40).padEnd(72, " ") + "G      1", wrapped.slice(40).padEnd(72, " ") + "G      2"].join("\n");
  assert.equal(cadExportNamesFolder(Buffer.from(igesText, "latin1"), folder, "iges"), false, "split at column 40 with padding: not this folder text");
  const igesWrapped = [wrapped.slice(0, 72) + "G      1", wrapped.slice(72).padEnd(72, " ") + "G      2"].join("\n");
  assert.equal(cadExportNamesFolder(Buffer.from(igesWrapped, "latin1"), folder, "iges"), true);
  assert.equal(cadExportNamesFolder(Buffer.from(`x${blanked}y`, "latin1"), folder, "iges"), true);
});

test("an export that still names its non-ASCII staging folder after the rewrite is refused and nothing is written", async () => {
  const root = await mkdtemp(join(tmpdir(), "gaps-guard-"));
  try {
    const dir = join(root, "dïr 模型 o'k");
    const runtime = {
      isUncertain: () => false,
      async mutate(_source: string, _bindings: string[], values: Array<{ path: string }>) {
        const path = values[0]!.path;
        // The DATA section names the staging folder (the header rewrite never touches DATA); STEP escapes, as the exporter writes them.
        const encoded = dirname(path).replace(/[^\x20-\x7e]/gu, (char) => {
          const code = char.codePointAt(0)!;
          return code < 0x100 ? `\\S\\${String.fromCharCode(code - 128)}` : `\\X2\\${code.toString(16).toUpperCase().padStart(4, "0")}\\X0\\`;
        }).replace(/'/gu, "''");
        await writeFile(path, `ISO-10303-21;\nHEADER;\nFILE_NAME('x','t',(''),(''),'a','b','c');\nENDSEC;\nDATA;\n#1=PRODUCT('${encoded}/geometry.step','','',());\nENDSEC;\nEND-ISO-10303-21;\n`, "latin1");
        return undefined;
      },
    } as unknown as PlasticityRuntime;
    const operations = new PlasticityOperations(runtime);
    const output = join(dir, "part.step");
    await assert.rejects(operations.exportStep([1], output), /still names its staging folder; the export was not written/);
    await assert.rejects(stat(output), /ENOENT/);
    assert.deepEqual((await readdir(dir)).filter((name) => !name.startsWith(".")), []);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

test("Parasolid header: KEY and FILE name the output, everything from END_OF_HEADER on is byte-identical, binary included", () => {
  const body = Buffer.concat([Buffer.from("**END_OF_HEADER" + "*".repeat(40) + "\n3: TRANSMIT FILE created by modeller version 3801167\n"), Buffer.from([0, 255, 128, 10, 59, 0x4b, 0x45, 0x59, 61])]);
  const header = (path: string) => Buffer.from(["**ABCDEFGHIJKLMNOPQRSTUVWXYZ**", "**PART1;", "MC=unknown;", "USER=unknown;", "FORMAT=binary;", `KEY=${path.replace(/\.x_b$/u, "")};`, `FILE=${path};`, "DATE=unknown;", "**PART2;", "SCH=SCH_3801167_38101;", ""].join("\n"), "latin1");
  const input = Buffer.concat([header("/Users/jane.doe/work/.plasticity-parasolid-xYz/geometry.x_b"), body]);
  const output = sanitizeParasolidHeader(input, "part.x_b");
  const text = output.subarray(0, output.indexOf("**END_OF_HEADER")).toString("latin1");
  assert.match(text, /\nKEY=part;\nFILE=part\.x_b;\nDATE=unknown;\n/);
  assert.ok(output.subarray(output.indexOf("**END_OF_HEADER")).equals(body));
  assert.equal(output.includes("jane.doe"), false);
  const noMarker = Buffer.from("no header marker");
  assert.equal(sanitizeParasolidHeader(noMarker, "a.x_t"), noMarker);
});
